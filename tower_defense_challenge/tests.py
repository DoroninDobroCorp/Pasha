"""
Автоматические тесты для задачи Tower Defense
=============================================

Запуск: python tests.py

Тесты проверяют, что твоё решение даёт правильное минимальное расстояние.
Точка патрулирования может отличаться (бывает несколько оптимальных),
но расстояние должно совпадать.
"""

import sys
from solution_template import find_patrol_point, calculate_total_distance


def run_test(name: str, towers: list[tuple[int, int]], expected_distance: int):
    """Запускает один тест."""
    try:
        result = find_patrol_point(towers)
        
        if result is None:
            print(f"❌ {name}: функция вернула None")
            return False
            
        patrol_x, total_distance = result
        
        # Проверяем, что возвращённое расстояние правильное
        if total_distance != expected_distance:
            print(f"❌ {name}")
            print(f"   Ожидалось расстояние: {expected_distance}")
            print(f"   Получено расстояние:  {total_distance}")
            return False
        
        # Проверяем, что для указанной точки расстояние действительно такое
        actual = calculate_total_distance(towers, patrol_x)
        if actual != total_distance:
            print(f"❌ {name}")
            print(f"   Точка {patrol_x} даёт расстояние {actual}, а не {total_distance}")
            return False
        
        print(f"✅ {name}")
        return True
        
    except Exception as e:
        print(f"❌ {name}: ошибка выполнения")
        print(f"   {type(e).__name__}: {e}")
        return False


def main():
    print("=" * 60)
    print("🎮 Tower Defense: Тестирование решения")
    print("=" * 60)
    print()
    
    tests = [
        # (название, башни, ожидаемое_расстояние)
        
        # Базовые тесты
        ("Тест 1: Пример из условия", 
         [(10, 80), (25, 30), (40, 90)], 
         450),
        
        ("Тест 2: Четыре башни", 
         [(10, 80), (25, 30), (40, 90), (60, 20)], 
         3250),
        
        ("Тест 3: Одинаковые приоритеты (медиана)", 
         [(0, 99), (50, 99), (100, 99)], 
         100),
        
        ("Тест 4: Одна критичная башня", 
         [(0, 99), (1000000000, 1)], 
         1000000000),
        
        # Граничные случаи
        ("Тест 5: Одна башня", 
         [(42, 50)], 
         0),
        
        ("Тест 6: Две башни, равные веса", 
         [(0, 50), (100, 50)], 
         5000),
        
        ("Тест 7: Все башни в одной точке", 
         [(10, 20), (10, 40), (10, 60)], 
         0),
        
        # Отрицательные координаты
        ("Тест 8: Отрицательные координаты", 
         [(-100, 50), (0, 50), (100, 50)], 
         10000),
        
        ("Тест 9: Все отрицательные", 
         [(-1000, 10), (-500, 30), (-100, 60)], 
         61000),
        
        # Проверка на правильность взвешенной медианы
        ("Тест 10: Много лёгких, одна тяжёлая слева",
         [(0, 1), (100, 99), (200, 99), (300, 99), (400, 99)],
         1000),  # дрон должен быть в 0 (вес 99 >> остальных)
        
        ("Тест 11: Много лёгких, одна тяжёлая справа",
         [(0, 99), (100, 99), (200, 99), (300, 99), (400, 1)],
         1000),  # дрон должен быть в 400
        
        ("Тест 12: Симметричный случай",
         [(0, 50), (100, 50)],
         5000),  # любая из двух точек даст тот же результат
        
        # Стресс-тест на большие числа
        ("Тест 13: Большие координаты",
         [(-1000000000, 50), (1000000000, 50)],
         100000000000),
        
        # Хитрый случай: взвешенная медиана не в "середине"
        ("Тест 14: Асимметричные веса",
         [(0, 99), (10, 99), (20, 99), (30, 99), (100, 1)],
         # Вес в точке 100 = 99, остальные по 1
         # Суммарный вес = 99 + 4 = 103
         # Половина = 51.5
         # Дрон должен быть в 100!
         340),
    ]
    
    passed = 0
    total = len(tests)
    
    for name, towers, expected in tests:
        if run_test(name, towers, expected):
            passed += 1
        print()
    
    print("=" * 60)
    print(f"Результат: {passed}/{total} тестов пройдено")
    print("=" * 60)
    
    if passed == total:
        print()
        print("🎉 Отлично! Все тесты пройдены!")
        print("   Попробуй запустить visualizer.py для визуализации")
        print()
    elif passed >= total * 0.7:
        print()
        print("👍 Хороший прогресс! Осталось немного доработать.")
        print()
    else:
        print()
        print("💪 Продолжай работать! Проверь подсказки в README.md")
        print()
    
    return 0 if passed == total else 1


if __name__ == "__main__":
    sys.exit(main())
